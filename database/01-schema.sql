BEGIN;
CREATE SCHEMA IF NOT EXISTS autoloca;
REVOKE ALL ON SCHEMA autoloca FROM PUBLIC;
SET search_path TO autoloca;
CREATE TABLE usuario (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 username varchar(80) NOT NULL UNIQUE,
 senha varchar(255) NOT NULL,
 nome varchar(255) NOT NULL,
 perfil varchar(255) NOT NULL CHECK (perfil IN ('CLIENTE','EMPRESA','BANCO'))
);
CREATE TABLE cliente (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 usuario_id bigint NOT NULL UNIQUE REFERENCES usuario(id),
 rg varchar(255) NOT NULL,
 cpf varchar(11) NOT NULL UNIQUE CHECK (cpf ~ '^[0-9]{11}$'),
 endereco varchar(255) NOT NULL,
 profissao varchar(255) NOT NULL
);
CREATE TABLE rendimento (
 cliente_id bigint NOT NULL REFERENCES cliente(id),
 empregador varchar(255) NOT NULL,
 valor numeric(12,2) NOT NULL CHECK(valor > 0)
);
CREATE TABLE automovel (
 foto bytea,
 foto_tipo varchar(255),
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 matricula varchar(255) NOT NULL UNIQUE,
 ano integer NOT NULL CHECK(ano BETWEEN 1900 AND 2100),
 marca varchar(255) NOT NULL,
 modelo varchar(255) NOT NULL,
 placa varchar(255) NOT NULL UNIQUE,
 diaria numeric(12,2) NOT NULL CHECK(diaria > 0),
 proprietario_id bigint NOT NULL REFERENCES usuario(id)
);
CREATE TABLE pedido (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 cliente_id bigint NOT NULL REFERENCES cliente(id),
 automovel_id bigint NOT NULL REFERENCES automovel(id),
 inicio date NOT NULL,
 fim date NOT NULL CHECK(fim > inicio),
 status varchar(255) NOT NULL CHECK(status IN ('EM_ANALISE','APROVADO','REPROVADO','CANCELADO','CONTRATADO')),
 valor_total numeric(12,2) NOT NULL CHECK(valor_total > 0),
 parecer varchar(2000),
 agente_id bigint REFERENCES usuario(id),
 criado_em timestamp(6) NOT NULL
);
CREATE TABLE contratocredito (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 banco_id bigint NOT NULL REFERENCES usuario(id),
 valor numeric(12,2) NOT NULL CHECK(valor > 0),
 parcelas integer NOT NULL CHECK(parcelas BETWEEN 1 AND 60)
);
CREATE TABLE contrato (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 pedido_id bigint NOT NULL UNIQUE REFERENCES pedido(id),
 proprietario_id bigint NOT NULL REFERENCES usuario(id),
 credito_id bigint UNIQUE REFERENCES contratocredito(id),
 assinado_em timestamp(6) NOT NULL
);
CREATE INDEX idx_pedido_cliente ON pedido(cliente_id);
CREATE INDEX idx_pedido_disponibilidade ON pedido(automovel_id,status,inicio,fim);
CREATE INDEX idx_rendimento_cliente ON rendimento(cliente_id);
REVOKE ALL ON ALL TABLES IN SCHEMA autoloca FROM PUBLIC;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA autoloca FROM PUBLIC;
DO $$ BEGIN
 IF EXISTS (SELECT FROM pg_roles WHERE rolname='anon') THEN
  REVOKE ALL ON SCHEMA autoloca FROM anon;
  REVOKE ALL ON ALL TABLES IN SCHEMA autoloca FROM anon;
  REVOKE ALL ON ALL SEQUENCES IN SCHEMA autoloca FROM anon;
 END IF;
 IF EXISTS (SELECT FROM pg_roles WHERE rolname='authenticated') THEN
  REVOKE ALL ON SCHEMA autoloca FROM authenticated;
  REVOKE ALL ON ALL TABLES IN SCHEMA autoloca FROM authenticated;
  REVOKE ALL ON ALL SEQUENCES IN SCHEMA autoloca FROM authenticated;
 END IF;
END $$;
COMMIT;
